    os.makedirs(SHARED, exist_ok=True)
    catalog = build_catalog()
    assert len(catalog["skus"]) == 120, f"expected 120 SKUs, got {len(catalog['skus'])}"

    catalog_json = json.dumps(catalog, indent=2, ensure_ascii=False)
    with open(os.path.join(SHARED, "catalog.json"), "w", encoding="utf-8") as f:
        f.write(catalog_json)
    for pid, data in PERSONAS.items():
        with open(os.path.join(SHARED, f"{pid}.json"), "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2, ensure_ascii=False)

    personas_json = json.dumps(PERSONAS, indent=2, ensure_ascii=False)
    personas_dest = os.path.join(ROOT, "frontend", "lib", "personas-data.json")
