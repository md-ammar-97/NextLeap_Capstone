def build_catalog():
    categories = CATEGORIES
    trust_type_map = {c["category_id"]: c["trust_template"] for c in categories}
    skus = []
    for cat_id, items in SKUS_BY_CATEGORY.items():
        types = trust_type_map[cat_id]
        for (slug, name, unit, price, mrp, veg, tags, desc, complements, fact_labels, has_anchor, deal) in items:
            sku_id = f"sku_{slug}"
            trust_facts = []
            for i, t in enumerate(types):
                label = fact_labels[i] if i < len(fact_labels) else ""
                trust_facts.append({"fact_id": f"{slug}_{t[:4]}", "type": t, "label": label})
            sku = {
                "sku_id": sku_id,
                "name": name,
                "category_id": cat_id,
                "unit": unit,
                "price": price,
                "mrp": mrp,
                "veg": veg,
                "image": None,  # placeholder-tile rendering for all SKUs in this pass; see docs/implementation_plan.md Pre-Flight note
                "tags": tags,
                "description": desc,
                "trust_facts": trust_facts,
                "out_of_stock": False,
                "complements": [f"sku_{c}" for c in complements],
            }
            if has_anchor:
                # reference price ~8-20% above ours, deterministic from price
                sku["anchor_price"] = {"retailer": "BigBasket", "price": round(price * 1.12 / 5) * 5}
            if deal:
                sku["deal"] = deal
            skus.append(sku)
    return {"categories": categories, "skus": skus}


